// Builds mobile/www from the desktop app's pages, so the phone app always matches the PC one.
//   - copies the shared pages, scripts, styles and assets
//   - writes defaults.js from main.js's DEFAULT_SETTINGS (one source of truth)
//   - adds the phone layer: mobile.js (stands in for Electron's preload bridge) and mobile.css
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(__dirname, 'www');

const SHARED = ['index.html', 'overlay.html', 'styles.css', 'overlay.css', 'faces.js', 'stream.js', 'app.js',
  'medialink.js', 'appaudio.js', 'room.js', 'watch.js', 'pcm-worklet.js'];
const MOBILE = ['mobile.js', 'mobile.css', 'mobile-overlay.js'];

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, 'assets'), { recursive: true });
fs.mkdirSync(path.join(OUT, 'vendor'), { recursive: true });

for (const f of SHARED) fs.copyFileSync(path.join(ROOT, f), path.join(OUT, f));
for (const f of MOBILE) fs.copyFileSync(path.join(__dirname, f), path.join(OUT, f));
for (const f of fs.readdirSync(path.join(ROOT, 'assets'))) {
  if (f === 'faces-sheet.png') continue;
  fs.copyFileSync(path.join(ROOT, 'assets', f), path.join(OUT, 'assets', f));
}
fs.copyFileSync(path.join(ROOT, 'node_modules/peerjs/dist/peerjs.min.js'), path.join(OUT, 'vendor/peerjs.min.js'));

// settings defaults straight from the desktop app
const main = fs.readFileSync(path.join(ROOT, 'main.js'), 'utf8');
const m = main.match(/const DEFAULT_SETTINGS = (\{[\s\S]*?\n\});/);
if (!m) throw new Error('DEFAULT_SETTINGS not found in main.js');
const version = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')).version;
fs.writeFileSync(path.join(OUT, 'defaults.js'),
  `// generated by mobile/build-www.js from main.js\nwindow.CONCHILLA_DEFAULTS = ${m[1]};\nwindow.CONCHILLA_VERSION = ${JSON.stringify(version)};\n`);

// main page: phone viewport, phone styles, the bridge before the app scripts, bundled PeerJS
let html = fs.readFileSync(path.join(OUT, 'index.html'), 'utf8');
const swap = (from, to) => {
  if (!html.includes(from)) throw new Error(`index.html changed: can't find ${from}`);
  html = html.replace(from, to);
};
swap('<meta charset="utf-8">', '<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover">');
swap('<link rel="stylesheet" href="styles.css">', '<link rel="stylesheet" href="styles.css">\n<link rel="stylesheet" href="mobile.css">');
swap('<script src="node_modules/peerjs/dist/peerjs.min.js"></script>',
  '<script src="defaults.js"></script>\n<script src="mobile.js"></script>\n<script src="vendor/peerjs.min.js"></script>');
swap('<body>', '<body class="mobile">');
fs.writeFileSync(path.join(OUT, 'index.html'), html);

// chat cards page (shown over the stream inside the app)
let ov = fs.readFileSync(path.join(OUT, 'overlay.html'), 'utf8');
if (!ov.includes('<script src="faces.js"></script>')) throw new Error('overlay.html changed');
ov = ov.replace('<script src="faces.js"></script>', '<script src="mobile-overlay.js"></script>\n<script src="faces.js"></script>')
  .replace('<body>', '<body class="mobile">')
  .replace('Enter send · Esc cancel', 'Enter sends');
fs.writeFileSync(path.join(OUT, 'overlay.html'), ov);

console.log(`www built (Conchilla ${version})`);
